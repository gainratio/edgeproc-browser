// Embeds SQLite's OPFS async proxy (sqlite3-opfs-async-proxy.js) as a
// TypeScript string constant. The SQLite Workers spawn the proxy from a
// same-origin Blob URL built from this constant, so installing the OPFS VFS
// never waits on a network fetch: sqlite3.mjs gives that spawn 4 s, and a
// saturated link (slow 4G under an 8-way chunk sync) could not deliver the
// script in time. Re-run after any change to the proxy; a test pins the
// generated module to the asset so the two cannot drift.
//
//   node scripts/generate-opfs-proxy-source.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const PROXY_FILE = "sqlite3-opfs-async-proxy.js";
export const SOURCE_MODULE = "opfsAsyncProxySource.ts";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
export const ASSETS_DIR = join(root, "src", "vector", "sqlite", "assets");

/** The TypeScript module text for a given proxy script. */
export function renderOpfsProxySource(script) {
	return [
		"// GENERATED by scripts/generate-opfs-proxy-source.mjs from",
		`// ${PROXY_FILE}. Do not edit; regenerate after changing the proxy.`,
		"",
		"/** SQLite's OPFS async proxy, verbatim, for spawning from a Blob URL. */",
		`export const OPFS_ASYNC_PROXY_SOURCE = ${JSON.stringify(script)};`,
		"",
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const script = readFileSync(join(ASSETS_DIR, PROXY_FILE), "utf8");
	writeFileSync(join(ASSETS_DIR, SOURCE_MODULE), renderOpfsProxySource(script));
	console.log(
		`wrote ${join(ASSETS_DIR, SOURCE_MODULE)} (${script.length} chars)`,
	);
}
